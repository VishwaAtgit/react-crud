#!/usr/bin/env bash
set -euo pipefail

# -------------------------------------------------------------------
# security-patch.sh
# Audits dependencies, applies fixes, validates, and commits to a branch.
#
# Usage:
#   chmod +x scripts/security-patch.sh
#   ./scripts/security-patch.sh
# -------------------------------------------------------------------

BRANCH="security/patch-$(date +%Y%m%d-%H%M%S)"
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log()  { echo -e "${GREEN}[security-patch]${NC} $*"; }
warn() { echo -e "${YELLOW}[security-patch]${NC} $*"; }
fail() { echo -e "${RED}[security-patch]${NC} $*"; exit 1; }

# 1. Pre-flight
log "Checking for uncommitted changes..."
if ! git diff --quiet || ! git diff --cached --quiet; then
  fail "Working tree is dirty. Commit or stash changes first."
fi

# 2. Backup lockfile
log "Backing up package-lock.json..."
cp package-lock.json package-lock.json.bak

# 3. Audit
log "Running npm audit..."
npm audit --json > audit-report.json 2>&1 || true

VULN_COUNT=$(node -e "
  try {
    const r = require('./audit-report.json');
    console.log(r.metadata?.vulnerabilities?.total ?? 0);
  } catch { console.log(0); }
")

if [ "$VULN_COUNT" = "0" ]; then
  log "No vulnerabilities found. Nothing to do."
  rm -f audit-report.json
  exit 0
fi

warn "Found $VULN_COUNT vulnerabilities. Applying fixes..."

# 4. Fix
npm audit fix 2>&1 | tee audit-fix.log || true

# 5. Validate
log "Validating build..."
npm run build || fail "Build failed after audit fix. See audit-fix.log."

log "Running tests..."
npm test -- --passWithNoTests --watchAll=false || fail "Tests failed after audit fix."

# 6. Commit to branch
log "Creating branch: $BRANCH"
git checkout -b "$BRANCH"
git add package.json package-lock.json
git commit -m "chore(security): apply npm audit fix ($VULN_COUNT vulns)"

log "Done. Push and open a PR:"
echo ""
echo "  git push origin $BRANCH"
echo "  gh pr create --title '🔒 Security patch – $(date +%Y-%m-%d)' --body 'Auto-generated by scripts/security-patch.sh'"
echo ""
log "To rollback:"
echo "  git checkout main"
echo "  git branch -D $BRANCH"
echo "  cp package-lock.json.bak package-lock.json"
echo "  npm ci"